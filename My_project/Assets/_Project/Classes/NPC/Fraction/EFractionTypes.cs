public enum EFractionTypes // Тип фракции (один вариант на фракцию)
{
    Regular, // Регулярная: системы, столица, заводы, экономика, оборона
    Hidden,  // Скрытая: без систем и столицы, без открытой инфраструктуры
    Super,   // Сверхсильная: системы, столица, замкнутая на себя, независимая экономика
    Enemy,   // Регулярный враг: стандартные системы/столица, агрессия по умолчанию
    Pirate,  // Пираты: разбросанные базы, без формальной столицы, но держат секторы
}
